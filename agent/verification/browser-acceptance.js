async page => {
  const passed = [];
  const errors = [];
  const requests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => requests.push({ method: request.method(), url: request.url() }));
  const check = (condition, description) => { if (!condition) throw new Error(description); passed.push(description); };
  const text = id => page.locator(`#${id}`).innerText();
  const status = value => page.waitForFunction(value => document.querySelector('#state').dataset.state === value, value);
  const settle = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  const point = async (name, index) => {
    await page.locator(`#cursor${name}`).click();
    await page.locator('#cursorIndex').fill(String(index));
    await page.locator('#locate').click();
    await settle();
    return page.locator(`#readout${name}`).getAttribute('data-word');
  };
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.goto('http://127.0.0.1:8102/');
  await status('ready'); await settle();
  check(await page.locator('.lane-label').count() === 16, '桌面显示16条通道');
  check((await text('period')) === '1 µs' && (await text('sampleCount')) === '1,000,000', '1µs/1百万点元数据正确');
  check(await page.locator('.hardware-note').innerText().then(t => t.includes('读取锁存器的速率')), '速率边界在页面可见');
  await page.locator('#single').click(); await status('triggered'); await settle();
  check((await text('triggerResult')).includes('索引 128'), 'D0首个上升沿在128');
  check((await text('viewExtent')) === '-128 µs → 384 µs', '靠近段首触发居中，前方保留无样本区');
  await page.locator('#triggerFrom').fill('500240');
  await page.locator('#triggerEdge').selectOption('falling');
  await page.locator('#single').click(); await status('triggered'); await settle();
  check((await text('triggerResult')).includes('500,248'), '缺口下降沿在500248');
  check((await text('viewExtent')) === '499.992 ms → 500.504 ms', '缺口触发点位于窗口正中');
  const expected = await page.evaluate(async () => {
    const bytes = await (await fetch('/api/samples')).arrayBuffer();
    return new DataView(bytes).getUint16(500248 * 2, true);
  });
  check(Number(await page.locator('#readoutA').getAttribute('data-word')) === expected && expected === 0x510c, '触发游标与服务原始小端样本一致');
  await page.locator('#fit').click(); await settle();
  check((await text('renderMode')).includes('桶内'), '整段启用聚合显示');
  check(Number(await point('A', 500248)) === expected, '聚合后游标仍读原始样本500248');
  const whole = await text('viewExtent');
  await page.locator('#zoomIn').click(); await settle();
  check((await text('viewExtent')) !== whole, '横向放大改变可见样本范围');
  const zoomed = await text('viewExtent');
  await page.locator('#panRight').click(); await settle();
  check((await text('viewExtent')) !== zoomed, '横向平移改变窗口位置');
  await page.locator('#plot').focus(); await page.keyboard.press('ArrowLeft'); await settle();
  check((await text('viewExtent')) === zoomed, '键盘反向平移恢复窗口');
  await page.locator('#zoomOut').click(); await settle();
  check((await text('viewExtent')) === whole, '横向缩小恢复整段范围');
  await page.locator('#showNotch').click(); await settle();
  const rect = await page.locator('#plot').boundingBox();
  await page.locator('#plot').click({ position: { x: (500248.25 - 500208) / 112 * rect.width, y: 50 } });
  await settle();
  check(await page.locator('#readoutA').getAttribute('data-index') === '500248', '画布鼠标坐标落到正确原始样本');
  await point('B', 500252);
  check((await text('delta')).includes('4 µs'), '缺口两侧游标测得4µs');
  await page.screenshot({ path: 'output/playwright/desktop-notch-dark.png', fullPage: true });
  await page.locator('#triggerChannel').selectOption('15');
  await page.locator('#triggerFrom').fill('0');
  await page.locator('#triggerEdge').selectOption('either');
  await page.locator('#single').click(); await status('untriggered');
  check((await text('state')).includes('未触发') && !(await page.locator('#stop').isEnabled()), '无边沿时保持停止并明确未触发');
  await page.locator('#restart').click();
  const requestsBefore = requests.length;
  await page.locator('#run').click(); await status('running');
  await page.waitForFunction(() => !document.querySelector('#liveIndex').textContent.includes('999,999'));
  await page.locator('#stop').click(); await status('stopped'); await settle();
  const paused = await text('liveIndex');
  await page.waitForTimeout(120);
  check((await text('liveIndex')) === paused, '停止期间显示进度与开入值冻结');
  const oldIndex = Number(paused.replace(/[^0-9]/g, ''));
  await page.locator('#run').click(); await status('running');
  await page.waitForFunction(oldIndex => Number(document.querySelector('#liveIndex').textContent.replace(/[^0-9]/g, '')) > oldIndex, oldIndex);
  await page.locator('#stop').click(); await status('stopped');
  check(requests.length === requestsBefore, '运行/停止/续播没有向服务或装置发送命令');
  check(Number((await text('liveIndex')).replace(/[^0-9]/g, '')) > oldIndex, '停止后运行接着原回放进度推进');
  await page.locator('#restart').click(); await page.locator('#run').click(); await status('full'); await settle();
  check(!(await page.locator('#run').isEnabled()) && (await text('liveIndex')).includes('999,999'), '到满深度自动停止且不循环覆盖');
  await page.waitForTimeout(120);
  check((await text('state')).includes('满深度') && (await text('sampleCount')) === '1,000,000', '满深度状态和完整段持续保留');
  await page.locator('#restart').click();
  await page.locator('#triggerChannel').selectOption('0');
  await page.locator('#triggerEdge').selectOption('falling');
  await page.locator('#triggerFrom').fill('500240');
  await page.locator('#showNotch').click();
  await page.locator('#triggerOnRun').check();
  await page.locator('#run').click(); await status('triggered');
  check((await text('triggerResult')).includes('500,248'), '运行布防在缺口沿触发后冻结');
  await page.locator('#theme').click(); await settle();
  await page.screenshot({ path: 'output/playwright/desktop-light.png', fullPage: true });
  check(await page.evaluate(() => document.documentElement.dataset.theme) === 'light', '明亮主题渲染完成');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload(); await status('ready'); await settle();
  check(!(await page.locator('#settingsPanel').getAttribute('open')), '窄屏默认收起设置');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '390px窄屏没有页面横向溢出');
  check(await page.locator('.lane-label').count() === 16, '窄屏保留16条数字泳道');
  await page.locator('#showNotch').click(); await point('A', 500248); await point('B', 500252);
  await page.screenshot({ path: 'output/playwright/narrow-dark.png', fullPage: true });
  await page.locator('#theme').click(); await settle();
  await page.screenshot({ path: 'output/playwright/narrow-light.png', fullPage: true });
  await page.locator('#settingsPanel summary').click();
  const fixture = 'F:/DDD/codeX/open_logic/agent/verification/fixtures/';
  await page.locator('#rawFile').setInputFiles(fixture + 'known.u16');
  await page.locator('#loadFile').click(); await status('ready'); await settle();
  check((await text('period')) === 'unknown' && (await text('dropped')) === 'unknown' && (await text('sequence')).includes('unknown'), '无元数据文件的周期/序号/丢样显示unknown');
  check(Number(await point('A', 1)) === 0x8001 && (await text('readoutA')).includes('unknown'), '本地文件原码正确且时间unknown');
  await page.locator('#metaFile').setInputFiles(fixture + 'known.json'); await page.locator('#loadFile').click(); await settle();
  check((await text('dropped')) === '2' && (await text('period')) === '1 µs', '本地JSON提供周期和丢样数');
  await point('A', 1);
  check((await text('readoutA')).includes('序号 unknown') && (await text('readoutA')).includes('名义'), '有丢样且缺失位置未知时，不伪造后续真实序号和实测时间');
  await page.locator('#rawFile').setInputFiles(fixture + 'half-sample.u16'); await page.locator('#loadFile').click(); await settle();
  check((await text('sampleCount')) === '4' && (await text('notice')).includes('偶数'), '坏文件拒绝且保留原段');
  await page.locator('#rawFile').setInputFiles(fixture + 'over-depth.u16');
  await page.locator('#metaFile').setInputFiles(fixture + 'over-depth.json');
  await page.locator('#loadFile').click(); await settle();
  check((await text('sampleCount')) === '1,000,000' && (await text('notice')).includes('后 9 点未载入'), '超深度文件只留首百万点并提示排除9点');
  check((await text('dropped')) === '3' && Number(await point('A', 0)) === 0x1234 && Number(await point('B', 999999)) === 0xabcd, '首尾原码保留，未被后段覆盖，排除点不混入丢样');
  check(errors.length === 0, '全过程没有JavaScript运行错误');
  check(requests.every(request => request.method === 'GET' && request.url.startsWith('http://127.0.0.1:8102/')), '所有浏览器网络访问只在本机8102且均为GET');
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.reload(); await status('ready');
  await page.locator('#showNotch').click(); await point('A', 500248); await point('B', 500252);
  await page.screenshot({ path: 'output/playwright/desktop-final.png', fullPage: true });
  return { passed: passed.length, checks: passed, errors, final: { source: await text('sourceBadge'), state: await text('state'), cursorA: await text('readoutA'), cursorB: await text('readoutB') } };
}
